const dictionaries = { en, ur, ar } as const;
export type Locale = keyof typeof dictionaries;

export function pickLocale(language: string): Locale {
  const base = language.toLowerCase().split("-")[0];
  return base === "ur" || base === "ar" ? base : "en";
}

export function translator(locale: Locale) {
  const words = dictionaries[locale];
  return (key: Key, values: Record<string, string | number> = {}) =>
    words[key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export type T = ReturnType<typeof translator>;

/** Is this one of the window's words? (Server messages are shown as they come.) */
export const isKey = (value: string): value is Key => Object.hasOwn(en, value);

export const directionOf = (locale: Locale) => (locale === "en" ? "ltr" : "rtl");

/** A time as the person's language writes it. */
export const formatTime = (iso: string, locale: Locale) =>
  new Date(iso).toLocaleString(locale === "en" ? undefined : locale, { dateStyle: "medium", timeStyle: "short" });
